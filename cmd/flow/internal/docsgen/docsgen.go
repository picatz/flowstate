// Package docsgen generates the reference documentation under docs/reference/,
// from the things that cannot drift.
//
// Four tables in this repository's prose were hand-maintained beside a registry
// that already knew the answer, and each one drifted the same silent way: the
// env-var table shipped ten variables short, the task table sent readers to a
// summary the schema had already outgrown, and a command added without a row was
// a capability nobody found. A table beside a source of truth is a second source
// of truth, and the second one is always the stale one.
//
// So these are derived, and pinned in CI with `git diff --exit-code` — the same
// mechanism that keeps committed generated code honest against `buf generate`. A
// change that adds a task, a flag, an RPC or a variable and does not regenerate
// fails in CI rather than in somebody's afternoon six weeks later.
//
// # Why live Go values rather than compiled descriptors
//
// docs/VISION.md warns that SourceCodeInfo — the leading comments a `.proto`
// carries — does not survive into the descriptors compiled into the binary:
// protoc-gen-go strips them, so a generator reading `protoregistry` finds field
// names and types and no prose. That is true and it is why nothing here reads a
// descriptor for documentation *text*.
//
// This generator runs inside the binary instead, over the same live values the
// running program uses: the task catalog (the registry, which is also what the
// GetCatalog RPC answers with), the cobra tree (whose Short, Long and Example
// fields are Go string literals and so are present at runtime), and the MCP tool
// table. Prose written in Go is prose a generator can read, and the derivation is
// from the *same object the code dispatches on* rather than from a parallel
// artifact — which is the stronger property anyway. Descriptors still supply
// everything structural, by way of the catalog: a task's field names, types, and
// required-ness come from protovalidate rules on the schema.
//
// The one thing that could change this is a custom protoc option carrying
// documentation into the descriptor set. That would be worth it only for prose
// that has nowhere else to live; today every sentence a reader needs is already
// a Go value.
//
// # Why a package, and why it is handed its sources
//
// The generator lived in `package main` beside the twenty-odd command
// implementations it documents, which made it a correctness gate — CI runs it
// and pins the bytes — that nothing could exercise except through its own
// output (#410). It is here now, behind [Sources]: every live value it derives
// from arrives as a parameter, so what it claims (this document describes the
// objects this binary dispatches on) is the thing the call site says out loud,
// and a test can hand it a smaller tree and get a document about that instead.
//
// `flow docs generate` is still the only caller that passes the real ones. This
// is a build step rather than a capability, and `internal/` is what says so.
//
// # Determinism
//
// Every listing here sorts, and the environment is cleared before the cobra tree
// is built — flag defaults are read from the environment at construction, so a
// developer with FLOWSTATE_ADDRESS set would otherwise generate a diff. Running
// the generator twice must produce identical bytes; TestGeneratedDocsAreStable
// is that assertion.
package docsgen

import (
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/spf13/cobra"
	"github.com/spf13/pflag"
)

// DefaultDir is where the generated reference lives, relative to the repository
// root.
const DefaultDir = "docs/reference"

// generatedNotice heads every generated file.
//
// Written into the file rather than left to a reviewer's memory: the first
// instinct on finding a wrong sentence in a document is to edit that document,
// and here that is the one action guaranteed not to work.
const generatedNotice = "<!-- Generated by `flow docs generate`. Do not edit; edit the source it is derived from. -->"

// Sources are the live values a reference is derived from.
//
// They are handed in rather than reached for, and that is the whole point of the
// package boundary: this generator's claim is that it documents the objects the
// running program dispatches on, and a parameter is where such a claim can be
// checked. cmd/flow passes the real ones.
type Sources struct {
	// NewRoot builds the cobra tree to document.
	//
	// A constructor rather than a built command, because the environment-mirror
	// probe rebuilds the tree once per documented variable: a flag default is
	// read from the environment when the command is constructed, so a shared
	// command would answer with whatever the environment held at the first call.
	NewRoot func() *cobra.Command

	// UseLine renders a command's usage line and FlagName a flag's spelling, the
	// way `flow help` renders each.
	//
	// Handed in rather than reimplemented here. Two spellings of one line is the
	// written-twice defect this repository keeps refinding, and a reference that
	// disagreed with `flow help` about what somebody types would be the version
	// nobody notices is wrong.
	UseLine  func(*cobra.Command) string
	FlagName func(*pflag.Flag) string

	// MCPTools is every tool `flow mcp` registers, in the order it registers
	// them. Which side a tool answers on is carried by a Go func value in the
	// dispatch table, which nothing outside can inspect, so it arrives as data.
	MCPTools []MCPTool

	// DefaultAddress is what `--address` defaults to with FLOWSTATE_ADDRESS
	// unset: one cell of the env-var table, and the only fact in it this package
	// cannot read from what it was handed.
	DefaultAddress string
}

// Generator renders the reference from one set of sources.
type Generator struct {
	src Sources
}

// New checks the sources and returns a generator over them.
//
// It refuses an incomplete set rather than filling one in. A missing NewRoot
// would render a CLI reference documenting no commands, and an empty MCPTools an
// agent surface with no tools — both perfectly valid markdown, both wrong in the
// one way CI's `git diff --exit-code` pin would report as a legitimate change.
// Failing closed here turns that into a message naming what is missing.
func New(src Sources) (*Generator, error) {
	var missing []string
	if src.NewRoot == nil {
		missing = append(missing, "NewRoot")
	}
	if src.UseLine == nil {
		missing = append(missing, "UseLine")
	}
	if src.FlagName == nil {
		missing = append(missing, "FlagName")
	}
	if len(src.MCPTools) == 0 {
		missing = append(missing, "MCPTools")
	}
	if src.DefaultAddress == "" {
		missing = append(missing, "DefaultAddress")
	}
	if len(missing) > 0 {
		return nil, fmt.Errorf("generating the reference needs these sources, which were not given: %s",
			strings.Join(missing, ", "))
	}

	return &Generator{src: src}, nil
}

// Generate writes every generated document into dir, returning their paths.
func (g *Generator) Generate(dir string) ([]string, error) {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return nil, fmt.Errorf("creating %s: %w", dir, err)
	}

	var paths []string
	for _, doc := range g.Documents() {
		path := filepath.Join(dir, doc.Name)
		if err := os.WriteFile(path, []byte(doc.Render()), 0o644); err != nil {
			return nil, fmt.Errorf("writing %s: %w", path, err)
		}
		paths = append(paths, path)
	}

	return paths, nil
}

// Document is one generated file: its name under the reference directory, and
// the function that renders its bytes.
//
// Exported as a pair rather than as a written document, because the tests that
// keep this honest are about the bytes: rendering twice and comparing catches an
// unsorted iteration, and rendering once and comparing against the committed
// file is CI's pin, made locally first.
type Document struct {
	Name   string
	Render func() string
}

// Documents is the whole set, in a fixed order.
func (g *Generator) Documents() []Document {
	return []Document{
		{Name: "tasks.md", Render: g.renderTaskReference},
		{Name: "cli.md", Render: g.renderCLIReference},
		{Name: "mcp.md", Render: g.renderMCPReference},
		{Name: "envvars.md", Render: g.renderEnvVarReference},
		{Name: "diagnostics.md", Render: g.renderDiagnosticCodeReference},
		{Name: "cel.md", Render: g.renderCELReference},
	}
}

// cell makes a string safe to put in a markdown table cell.
func cell(text string) string {
	text = strings.ReplaceAll(text, "|", `\|`)
	text = strings.ReplaceAll(text, "\n", " ")

	return strings.TrimSpace(text)
}

// codeOrEmpty renders a value as code, or as nothing when there is none.
func codeOrEmpty(value string) string {
	if value == "" || value == "[]" {
		return ""
	}

	return "`" + cell(value) + "`"
}

// orDash gives an empty cell something to hold, since a blank one reads as an
// omission rather than as an absence.
func orDash(value string) string {
	if value == "" {
		return "—"
	}

	return value
}

// yesNo renders a boolean column.
func yesNo(value bool) string {
	if value {
		return "yes"
	}

	return "no"
}

// codeList renders names as an inline list, sorted.
//
// Sorted rather than kept in the catalog's order, because the order a listing
// arrives in is not something the catalog promises, and a document whose lines
// move for no reason is a document CI's pin fails on for no reason.
func codeList(names []string) string {
	var out []string
	for _, name := range slices.Sorted(slices.Values(names)) {
		out = append(out, "`"+cell(name)+"`")
	}
	if len(out) == 0 {
		return "none"
	}

	return strings.Join(out, ", ")
}
