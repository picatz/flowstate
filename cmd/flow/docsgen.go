// renderEnvVarReference documents every variable this build reads.
//
// The table VISION names as the proven drifter — it shipped ten variables short
// — so it is the one with the most machinery behind it. The prose is written by
// hand and the *set* is not: see [documentedEnvironmentVariables].
func renderEnvVarReference() string {
	var b strings.Builder

	b.WriteString(generatedNotice + "\n\n")
	b.WriteString("# Environment variable reference\n\n")
	b.WriteString("Every variable this build reads. There is no single registration point to derive\n")
	b.WriteString("this from (a variable is read where it is needed), so the prose is written by\n")
	b.WriteString("hand in `cmd/flow/docsgen.go` and the *set* is enforced: a test parses every\n")
	b.WriteString("non-test file under `cmd/` and `pkg/`, collects the variable names and the\n")
	b.WriteString("`os.Getenv`/`os.LookupEnv` call sites, and fails on a read this table does not\n")
	b.WriteString("carry or an entry nothing reads any more.\n\n")
	b.WriteString("Where a variable is the default of a flag, the flag wins when both are given.\n")
	b.WriteString("[cli.md](cli.md) says which flag each one feeds.\n\n")

	b.WriteString("| Variable | Default | Purpose | Read in |\n|---|---|---|---|\n")
	for _, variable := range documentedEnvironmentVariables() {
		fmt.Fprintf(&b, "| `%s` | %s | %s | `%s` |\n",
			cell(variable.name), orDash(codeOrEmpty(variable.value)), cell(variable.purpose), cell(variable.read))
	}

	return b.String()
}

// renderDiagnosticCodeReference documents every stable diagnostic code this
// build assigns.
//
// Derived from [v1.DiagnosticCodes] — the same registry flowfile's
// diagnostic-construction sites assign from — for the reason every generated
// document here exists: a code list kept by hand beside the code that assigns
// codes is a second source of truth, and CLAUDE.md's four proven driftors were
// all exactly that shape. TestDiagnosticCodesAreAssigned, in the flowfile
// package, is the other half — it holds the *registry* to the codes actually
// used, so this file documenting a code nothing assigns (or missing one that
// is assigned) fails there rather than only being wrong here.
func renderDiagnosticCodeReference() string {
	var b strings.Builder

	b.WriteString(generatedNotice + "\n\n")
	b.WriteString("# Diagnostic code reference\n\n")
	b.WriteString("Every stable `code` a [`Diagnostic`](../../proto/flowstate/v1/flowstate.proto)\n")
	b.WriteString("carries, so a program can decide what a validation failure *is* without parsing\n")
	b.WriteString("`message`, which this project reserves the right to reword. Deliberately small:\n")
	b.WriteString("only the classes an agent is actually expected to branch on have their own code,\n")
	b.WriteString("everything else is `general`, and that is documented rather than pretended away.\n\n")

	b.WriteString("| Code | Meaning |\n|---|---|\n")
	for _, info := range v1.DiagnosticCodes() {
		fmt.Fprintf(&b, "| `%s` | %s |\n", cell(string(info.Code)), cell(info.Description))
	}

	return b.String()
}

// cell makes a string safe to put in a markdown table cell.
func cell(text string) string {
	text = strings.ReplaceAll(text, "|", `\|`)
	text = strings.ReplaceAll(text, "\n", " ")

	return strings.TrimSpace(text)
}

// codeOrEmpty renders a value as code, or as nothing when there is none.
func codeOrEmpty(value string) string {
	if value == "" || value == "[]" {
		return ""
	}

	return "`" + cell(value) + "`"
}

// orDash gives an empty cell something to hold, since a blank one reads as an
// omission rather than as an absence.
func orDash(value string) string {
	if value == "" {
		return "—"
	}

	return value
}

// yesNo renders a boolean column.
func yesNo(value bool) string {
	if value {
		return "yes"
	}

	return "no"
}

// codeList renders names as an inline list, sorted.
//
// Sorted rather than kept in the catalog's order, because the order a listing
// arrives in is not something the catalog promises, and a document whose lines
// move for no reason is a document CI's pin fails on for no reason.
func codeList(names []string) string {
	var out []string
	for _, name := range slices.Sorted(slices.Values(names)) {
		out = append(out, "`"+cell(name)+"`")
	}
	if len(out) == 0 {
		return "none"
	}

	return strings.Join(out, ", ")
}
