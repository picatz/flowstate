// Reference documentation, generated from the things that cannot drift.
//
// Four tables in this repository's prose were hand-maintained beside a registry
// that already knew the answer, and each one drifted the same silent way: the
// env-var table shipped ten variables short, the task table sent readers to a
// summary the schema had already outgrown, and a command added without a row was
// a capability nobody found. A table beside a source of truth is a second source
// of truth, and the second one is always the stale one.
//
// So these are derived, and pinned in CI with `git diff --exit-code` — the same
// mechanism that keeps committed generated code honest against `buf generate`. A
// change that adds a task, a flag, an RPC or a variable and does not regenerate
// fails in CI rather than in somebody's afternoon six weeks later.
//
// # Why live Go values rather than compiled descriptors
//
// docs/VISION.md warns that SourceCodeInfo — the leading comments a `.proto`
// carries — does not survive into the descriptors compiled into the binary:
// protoc-gen-go strips them, so a generator reading `protoregistry` finds field
// names and types and no prose. That is true and it is why nothing here reads a
// descriptor for documentation *text*.
//
// This generator runs inside the binary instead, over the same live values the
// running program uses: [v1.Catalog] (the registry, which is also what the
// GetCatalog RPC answers with), [newRootCommand] (the cobra tree, whose Short,
// Long and Example fields are Go string literals and so are present at runtime),
// and the MCP tool table. Prose written in Go is prose a generator can read, and
// the derivation is from the *same object the code dispatches on* rather than
// from a parallel artifact — which is the stronger property anyway. Descriptors
// still supply everything structural, by way of the catalog: a task's field
// names, types, and required-ness come from protovalidate rules on the schema.
//
// The one thing that could change this is a custom protoc option carrying
// documentation into the descriptor set. That would be worth it only for prose
// that has nowhere else to live; today every sentence a reader needs is already
// a Go value.
//
// # Determinism
//
// Every listing here sorts, and the environment is cleared before the cobra tree
// is built — flag defaults are read from the environment at construction, so a
// developer with FLOWSTATE_ADDRESS set would otherwise generate a diff. Running
// the generator twice must produce identical bytes; TestGeneratedDocsAreStable
// is that assertion.

// docsReferenceDir is where the generated reference lives, relative to the
// repository root.
const docsReferenceDir = "docs/reference"

// generatedNotice heads every generated file.
//
// Written into the file rather than left to a reviewer's memory: the first
// instinct on finding a wrong sentence in a document is to edit that document,
// and here that is the one action guaranteed not to work.
const generatedNotice = "<!-- Generated by `flow docs generate`. Do not edit; edit the source it is derived from. -->"

// newDocsCommand builds the hidden `docs` command.
//
// Hidden and registered beside `flow man` in execute.go rather than in
// [newRootCommand], for the same reason that one is: it is a build step, not
// something a user types. Keeping it out of the root constructor also keeps it
// out of the command tree the README's pin tests and the generated CLI reference
// walk, which is correct — `flow docs generate` documents the product, and is
// not part of it.
func newDocsCommand() *cobra.Command {
	docs := &cobra.Command{
		Use:                   "docs",
		Short:                 "Generate reference documentation",
		Hidden:                true,
		SilenceUsage:          true,
		DisableFlagsInUseLine: true,
	}

	generate := &cobra.Command{
		Use:          "generate",
		Short:        "Write the generated reference into docs/reference/",
		Args:         cobra.NoArgs,
		SilenceUsage: true,
		RunE: func(cmd *cobra.Command, _ []string) error {
			dir, err := cmd.Flags().GetString("dir")
			if err != nil {
				return err
			}

			written, err := generateReference(dir)
			if err != nil {
				return err
			}

			for _, path := range written {
				fmt.Fprintln(cmd.OutOrStdout(), path)
			}

			return nil
		},
	}
	generate.Flags().String("dir", docsReferenceDir, "directory to write the generated reference into")

	docs.AddCommand(generate)

	return docs
}

// generateReference writes every generated document, returning their paths.
func generateReference(dir string) ([]string, error) {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return nil, fmt.Errorf("creating %s: %w", dir, err)
	}

	var paths []string
	for _, doc := range referenceDocuments() {
		path := filepath.Join(dir, doc.name)
		if err := os.WriteFile(path, []byte(doc.render()), 0o644); err != nil {
			return nil, fmt.Errorf("writing %s: %w", path, err)
		}
		paths = append(paths, path)
	}

	return paths, nil
}

// referenceDocument is one generated file.
type referenceDocument struct {
	name   string
	render func() string
}

// referenceDocuments is the whole set, in a fixed order.
func referenceDocuments() []referenceDocument {
	return []referenceDocument{
		{name: "tasks.md", render: renderTaskReference},
		{name: "cli.md", render: renderCLIReference},
		{name: "mcp.md", render: renderMCPReference},
		{name: "envvars.md", render: renderEnvVarReference},
		{name: "diagnostics.md", render: renderDiagnosticCodeReference},
	}
}

// renderTaskReference documents what this build can execute.
//
// Derived from [v1.Catalog], which is the message the GetCatalog RPC returns
// unchanged — so the document and the RPC cannot describe different tasks. That
// is the point of going through the catalog rather than walking the registry
// here: a second traversal of the registry would be a second answer to "what can
// this build run", and the two would eventually differ in some detail nobody
// compares.
//
// Built-ins only. A plugin's tasks are a property of a deployment, not of this
// binary, and `flow plugins` is the command that asks a deployment.
func renderTaskReference() string {
	catalog := v1.Catalog()

	var b strings.Builder

	b.WriteString(generatedNotice + "\n\n")
	b.WriteString("# Task reference\n\n")
	b.WriteString("Every task this build can execute, with the inputs it takes and the outputs it\n")
	b.WriteString("produces. Derived from the task registry (the same `TaskCatalog` the `GetCatalog`\n")
	b.WriteString("RPC and `flow tasks` answer with), so a task cannot behave one way and document\n")
	b.WriteString("another.\n\n")
	b.WriteString("A plugin's tasks are not here: what a plugin adds is a property of a deployment\n")
	b.WriteString("rather than of this binary, and `flow plugins` is what asks a deployment.\n\n")

	b.WriteString("## Tasks\n\n")
	for _, task := range catalog.GetTasks() {
		fmt.Fprintf(&b, "### `%s`\n\n", task.GetName())
		if summary := task.GetSummary(); summary != "" {
			fmt.Fprintf(&b, "%s\n\n", summary)
		}

		writeTaskFields(&b, "Inputs", task.GetInputs(), true)
		writeTaskFields(&b, "Outputs", task.GetOutputs(), false)
	}

	b.WriteString("## Expressions\n\n")
	fmt.Fprintf(&b, "Values are reached through these roots: %s.\n\n", codeList(catalog.GetValueRoots()))
	fmt.Fprintf(&b, "Duration constructors, available to every expression: %s.\n\n", codeList(catalog.GetDurationUnits()))
	fmt.Fprintf(&b, "Inside a wait's own expressions (`sleep:`, `wait_until:`, and a signal's\n"+
		"`timeout:`) and nowhere else, `%s` is bound to the evaluation moment.\n\n",
		catalog.GetNowIdentifier())
	fmt.Fprintf(&b, "CEL libraries every expression reaches: %s.\n\n", codeList(catalog.GetCelLibraries()))

	b.WriteString("### Functions\n\n")
	b.WriteString("What those libraries add. A macro is expanded by the parser rather than called by\n")
	b.WriteString("the evaluator, so its name is not its whole call form; the example is.\n\n")
	b.WriteString("| Function | Library | Kind | Example |\n|---|---|---|---|\n")
	for _, fn := range catalog.GetCelFunctions() {
		kind := "function"
		if fn.GetMacro() {
			kind = "macro"
		}
		example := "—"
		if fn.GetExample() != "" {
			example = "`" + cell(fn.GetExample()) + "`"
		}
		fmt.Fprintf(&b, "| `%s` | `%s` | %s | %s |\n",
			cell(fn.GetName()), cell(fn.GetLibrary()), kind, example)
	}

	return b.String()
}

// writeTaskFields renders one task's inputs or outputs.
func writeTaskFields(b *strings.Builder, heading string, fields []*v1.TaskField, required bool) {
	fmt.Fprintf(b, "**%s**\n\n", heading)

	if len(fields) == 0 {
		b.WriteString("None.\n\n")

		return
	}

	if required {
		b.WriteString("| Name | Type | Required | Deferred | Bounds |\n|---|---|---|---|---|\n")
	} else {
		b.WriteString("| Name | Type | Bounds |\n|---|---|---|\n")
	}

	for _, field := range fields {
		// The bounds the schema and the task already carry, the same phrases `flow
		// tasks <name>` prints, because they come from the same field on the same
		// message. A reference that omitted them would send a reader who wants to
		// know how long a `credential:` may be to the proto, which is the drift this
		// document exists to prevent.
		bounds := "none"
		if constraints := field.GetConstraints(); len(constraints) > 0 {
			bounds = cell(strings.Join(constraints, "; "))
		}

		if !required {
			fmt.Fprintf(b, "| `%s` | `%s` | %s |\n",
				cell(field.GetName()), cell(field.GetType()), bounds)

			continue
		}

		fmt.Fprintf(b, "| `%s` | `%s` | %s | %s | %s |\n",
			cell(field.GetName()), cell(field.GetType()),
			yesNo(field.GetRequired()), yesNo(field.GetDeferred()), bounds)
	}
	b.WriteString("\n")
}

// renderCLIReference documents the command line, from the cobra tree.
//
// `newRootCommand` exists to be asked — the README's command pin tests already
// walk it — and this is the deeper form of the same question: not only which
// commands exist but what each one takes. Hidden commands are left out on the
// grounds that a hidden command is a build step rather than a capability.
func renderCLIReference() string {
	var commands []cliCommand
	var mirrors map[string]string

	withCleanEnvironment(func() {
		commands = describeCommands(newRootCommand())
		mirrors = environmentMirrors()
	})

	var b strings.Builder

	b.WriteString(generatedNotice + "\n\n")
	b.WriteString("# CLI reference\n\n")
	b.WriteString("Every command and flag `flow` has, derived from the cobra tree the binary builds\n")
	b.WriteString("at startup. [docs/CLI.md](../CLI.md) is the philosophy this surface holds itself\n")
	b.WriteString("to; this is the enumeration.\n\n")
	b.WriteString("A flag whose default comes from an environment variable says so. Those defaults\n")
	b.WriteString("are read when the command tree is built, which is why the generator clears the\n")
	b.WriteString("environment first: otherwise this document would record whoever ran it.\n\n")

	for _, cmd := range commands {
		fmt.Fprintf(&b, "## `%s`\n\n", cmd.path)
		if cmd.short != "" {
			fmt.Fprintf(&b, "%s\n\n", cmd.short)
		}
		fmt.Fprintf(&b, "```\n%s\n```\n\n", cmd.use)
		if cmd.long != "" && cmd.long != cmd.short {
			fmt.Fprintf(&b, "%s\n\n", cmd.long)
		}
		if cmd.example != "" {
			b.WriteString("Examples:\n\n")
			fmt.Fprintf(&b, "```sh\n%s\n```\n\n", cmd.example)
		}

		if len(cmd.flags) == 0 {
			continue
		}

		b.WriteString("| Flag | Type | Default | Environment | Description |\n|---|---|---|---|---|\n")
		for _, flag := range cmd.flags {
			fmt.Fprintf(&b, "| `%s` | `%s` | %s | %s | %s |\n",
				cell(flag.spelling), cell(flag.kind), orDash(codeOrEmpty(flag.defValue)),
				orDash(codeOrEmpty(mirrors[cmd.path+" "+flag.name])), cell(flag.usage))
		}
		b.WriteString("\n")
	}

	return b.String()
}

// cliCommand is one command, as the reference needs it.
type cliCommand struct {
	path    string
	use     string
	short   string
	long    string
	example string
	flags   []cliFlag
}

// cliFlag is one flag of one command.
type cliFlag struct {
	name     string
	spelling string
	kind     string
	defValue string
	usage    string
}

// describeCommands walks the tree, parents before children and siblings by name.
//
// cobra's own `help` and `completion` are left out for the reason the README's
// pin test leaves them out: they are the framework's commands rather than this
// tool's, and documenting them here would be describing cobra.
func describeCommands(root *cobra.Command) []cliCommand {
	out := []cliCommand{describeCommand(root)}

	children := slices.Clone(root.Commands())
	sort.Slice(children, func(i, j int) bool { return children[i].Name() < children[j].Name() })

	for _, child := range children {
		switch {
		case child.Hidden, child.Name() == "help", child.Name() == "completion":
			continue
		}
		out = append(out, describeCommands(child)...)
	}

	return out
}

// describeCommand reads one command's own documentation.
func describeCommand(cmd *cobra.Command) cliCommand {
	described := cliCommand{
		path:    cmd.CommandPath(),
		use:     useLine(cmd),
		short:   strings.TrimSpace(cmd.Short),
		long:    strings.TrimSpace(cmd.Long),
		example: strings.TrimSpace(cmd.Example),
	}

	seen := map[string]bool{}
	add := func(f *pflag.Flag) {
		if f.Hidden || seen[f.Name] {
			return
		}
		seen[f.Name] = true

		described.flags = append(described.flags, cliFlag{
			name:     f.Name,
			spelling: flagName(f),
			kind:     f.Value.Type(),
			defValue: f.DefValue,
			usage:    strings.TrimSpace(f.Usage),
		})
	}

	// Local flags only. An inherited flag is documented on the command that
	// declares it, and repeating `--verbose` on all twenty-two commands is a page
	// nobody reads twice.
	cmd.LocalFlags().VisitAll(add)

	sort.Slice(described.flags, func(i, j int) bool { return described.flags[i].name < described.flags[j].name })

	return described
}

// environmentMirrors reports which flag defaults come from which variable, keyed
// by "<command path> <flag>".
//
// Derived rather than declared, because pflag has nowhere to record it: a flag
// whose default is `os.Getenv("FLOWSTATE_ADDRESS")` looks exactly like one whose
// default is a constant. So each documented variable is set to a value nothing
// else could produce, the whole command tree is rebuilt, and any flag defaulting
// to that value is the flag that variable feeds.
//
// It answers for the mirrors and nothing else. A variable read as a *condition*
// rather than as a default — `FLOWSTATE_VERBOSE_LOGGING == "true"`, which yields
// a bool — cannot be seen this way, and the env-var reference says where those
// are read in prose. This finds every one that is genuinely a default, including
// one added tomorrow to a flag nobody remembers to document.
func environmentMirrors() map[string]string {
	mirrors := map[string]string{}

	for i, variable := range documentedEnvironmentVariables() {
		if variable.family {
			continue
		}

		sentinel := fmt.Sprintf("flowstate-docsgen-sentinel-%d", i)
		if err := os.Setenv(variable.name, sentinel); err != nil {
			continue
		}

		for _, cmd := range describeCommands(newRootCommand()) {
			for _, flag := range cmd.flags {
				if strings.Contains(flag.defValue, sentinel) {
					mirrors[cmd.path+" "+flag.name] = variable.name
				}
			}
		}

		_ = os.Unsetenv(variable.name)
	}

	return mirrors
}

// withCleanEnvironment runs f with every variable this reference documents
// removed, and puts the environment back afterwards.
//
// Both halves matter. Without the clearing, the generated CLI reference records
// the machine it ran on and CI's pin fails for the wrong reason. Without the
// restoring, the generator would be a command that quietly unconfigures the
// process it runs in.
func withCleanEnvironment(f func()) {
	saved := map[string]string{}
	for _, variable := range documentedEnvironmentVariables() {
		if value, found := os.LookupEnv(variable.name); found {
			saved[variable.name] = value
			_ = os.Unsetenv(variable.name)
		}
	}

	defer func() {
		for name, value := range saved {
			_ = os.Setenv(name, value)
		}
	}()

	f()
}

// renderMCPReference documents the agent surface.
//
// The tool set is derived: [workflowServiceMethods] is what `flow mcp` registers,
// asserted against the service descriptor in both directions by its own tests, so
// walking it here documents exactly what an agent connects to.
func renderMCPReference() string {
	var b strings.Builder

	b.WriteString(generatedNotice + "\n\n")
	b.WriteString("# MCP tool reference\n\n")
	b.WriteString("`flow mcp` serves the control plane to an agent over stdio. Every WorkflowService\n")
	b.WriteString("RPC becomes one tool, discovered by walking the service descriptor rather than\n")
	b.WriteString("kept in a list, so an RPC added to the schema is a tool the day the code is\n")
	b.WriteString("regenerated.\n\n")
	b.WriteString("**Answers locally** means the tool needs no server and no Temporal: authoring\n")
	b.WriteString("(validate, compile, read the catalog, rehearse a run) works with nothing else\n")
	b.WriteString("stood up. The rest address durable runs, which only a server has, and say so\n")
	b.WriteString("rather than failing opaquely when `--address` was not given.\n\n")

	b.WriteString("| Tool | Answers | Request message |\n|---|---|---|\n")
	for _, tool := range mcpTools() {
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n", cell(tool.name), tool.reach(), orDash(codeOrEmpty(tool.request)))
	}
	b.WriteString("\n")

	for _, tool := range mcpTools() {
		fmt.Fprintf(&b, "## `%s`\n\n", tool.name)
		fmt.Fprintf(&b, "%s\n\n", tool.description)
	}

	return b.String()
}

// mcpTool is one tool as the reference describes it.
type mcpTool struct {
	name        string
	description string
	request     string
	local       bool
}

func (t mcpTool) reach() string {
	if t.local {
		return "locally"
	}

	return "via a server"
}

// mcpLocalTools names the tools that answer in this process.
//
// Hand-kept, and deliberately hard to add to. Which side a tool answers on is
// carried by the dispatch closure in mcp.go — a Go func value, which nothing can
// inspect from outside — so it is written down once here rather than guessed
// from a description's wording. [TestEveryMCPToolHasALocality] holds this to the
// registered tool set in both directions, so a tool added without a decision
// about where it answers fails rather than being documented wrong.
var mcpLocalTools = map[string]bool{
	"Validate":   true,
	"Compile":    true,
	"GetCatalog": true,
}

// mcpTools describes every tool `flow mcp` registers, in the order it registers
// them.
func mcpTools() []mcpTool {
	var tools []mcpTool
	for _, method := range workflowServiceMethods() {
		tools = append(tools, mcpTool{
			name:        mcpToolName(method.name),
			description: mcpToolDescription(method.name),
			request:     string(method.input.FullName()),
			local:       mcpLocalTools[method.name],
		})
	}

	tools = append(tools, mcpTool{
		name:        runLocalToolName,
		description: runLocalToolDescription,
		local:       true,
	})
	tools = append(tools, mcpTool{
		name:        testToolName,
		description: testToolDescription,
		local:       true,
	})

	return tools
}

// environmentVariable is one variable this build reads.
type environmentVariable struct {
	// name is the variable, or the family's spelling where family is set.
	name string

	// value is what happens when it is unset.
	value string

	// purpose is what setting it does.
	purpose string

	// read is where the process reads it, as a package path or file — so a reader
	// who doubts the sentence can go and check it.
	read string

	// family marks an entry that stands for a *set* of variables rather than one
	// name: `FLOWSTATE_SECRET_<NAME>`, the OTLP exporter's own configuration. The
	// drift test does not require a literal for these, and the mirror probe skips
	// them, because there is no single name to set.
	family bool
}

