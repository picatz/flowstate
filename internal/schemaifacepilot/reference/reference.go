// Package reference contains the prose-bearing documentation half of the issue
// #1227 pilot. It is separate so static or linked-descriptor-only binding does
// not pull the schema's generated comments into a binary.
package reference

import (
	"bytes"
	"fmt"
	"io"
	"strings"

	"github.com/picatz/flowstate/internal/schemaifacepilot"
	flowstatev1 "github.com/picatz/flowstate/pkg/flowstate/v1"
	"github.com/picatz/flowstate/pkg/flowstate/v1/protodoc"
	"google.golang.org/protobuf/reflect/protoreflect"
)

// GenerateGet demonstrates descriptor-derived contract documentation while
// leaving spelling and usage copy in the command-owned selection.
func GenerateGet(out io.Writer) error {
	linked := (&flowstatev1.GetRequest{}).ProtoReflect().Descriptor()
	if err := schemaifacepilot.ValidateSelections(linked, schemaifacepilot.GetSelections); err != nil {
		return err
	}

	var rendered bytes.Buffer
	fmt.Fprintln(&rendered, "<!-- Generated by the issue #1227 pilot. Do not edit. -->")
	fmt.Fprintln(&rendered)
	fmt.Fprintln(&rendered, "# `flow get` selected request fields")
	fmt.Fprintln(&rendered)
	if comment, ok := protodoc.CommentOf(linked); ok {
		fmt.Fprintln(&rendered, comment)
		fmt.Fprintln(&rendered)
	}
	fmt.Fprintln(&rendered, "| CLI input | Request field | Presence | Schema constraints | Schema field prose | Command-owned usage |")
	fmt.Fprintln(&rendered, "|---|---|---|---|---|---|")
	for _, selection := range schemaifacepilot.GetSelections {
		field := linked.Fields().ByName(selection.ProtoName)
		constraints := fieldConstraints(field)
		if len(constraints) == 0 {
			constraints = []string{"—"}
		}
		prose := "—"
		if comment, ok := protodoc.CommentOf(field); ok {
			prose = comment
		}
		fmt.Fprintf(&rendered, "| %s | `%s` | %s | %s | %s | %s |\n",
			surfaceSpelling(selection), selection.ProtoName, presenceLabel(field),
			escapeTable(strings.Join(constraints, "; ")), escapeTable(prose), escapeTable(selection.Usage))
	}
	_, err := out.Write(rendered.Bytes())
	return err
}

func presenceLabel(field protoreflect.FieldDescriptor) string {
	switch {
	case flowstatev1.RequiredInput(field):
		return "required"
	case field.HasPresence():
		return "optional; unset stays absent"
	default:
		return "optional; unset uses the scalar zero value"
	}
}

func fieldConstraints(field protoreflect.FieldDescriptor) []string {
	return flowstatev1.FieldConstraints(field)
}

func surfaceSpelling(selection schemaifacepilot.Selection) string {
	if selection.Positional {
		return "`<" + selection.SurfaceName + ">`"
	}
	return "`--" + selection.SurfaceName + "`"
}

func escapeTable(value string) string {
	value = strings.ReplaceAll(value, "|", "\\|")
	return strings.ReplaceAll(value, "\n", " ")
}
