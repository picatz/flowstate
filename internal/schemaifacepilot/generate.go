package schemaifacepilot

import (
	"fmt"
	"go/format"
	"io"

	flowstatev1 "github.com/picatz/flowstate/pkg/flowstate/v1"
)

// GenerateStaticGet writes the deliberately single-command static pilot. The
// generator refuses descriptor drift before emitting direct Go assignments.
func GenerateStaticGet(out io.Writer) error {
	descriptor := (&flowstatev1.GetRequest{}).ProtoReflect().Descriptor()
	fields, err := selectFields(descriptor, GetSelections)
	if err != nil {
		return err
	}
	workflow, ok := selectionByName(fields, "workflow_id")
	if !ok {
		return fmt.Errorf("schema interface pilot: workflow_id selection missing")
	}
	run, ok := selectionByName(fields, "run_id")
	if !ok {
		return fmt.Errorf("schema interface pilot: run_id selection missing")
	}

	source := fmt.Sprintf(`// Code generated by the issue #1227 pilot. DO NOT EDIT.

package schemaifacepilot

import (
	flowstatev1 "github.com/picatz/flowstate/pkg/flowstate/v1"
	"github.com/spf13/pflag"
	"google.golang.org/protobuf/proto"
)

// StaticGetBinding is generated for the two fields selected by GetSelections.
// It does not construct or duplicate a Cobra command.
type StaticGetBinding struct {
	request *flowstatev1.GetRequest
	flags *pflag.FlagSet
	runID string
}

func NewStaticGetBinding(flags *pflag.FlagSet) *StaticGetBinding {
	binding := &StaticGetBinding{request: &flowstatev1.GetRequest{}, flags: flags}
	flags.StringVar(&binding.runID, %q, "", %q)
	return binding
}

func (b *StaticGetBinding) Apply(workflowID string) error {
	b.request.%s = workflowID
	if b.flags.Changed(%q) && b.runID != "" {
		b.request.%s = proto.String(b.runID)
	}
	return flowstatev1.Validate(b.request)
}

func (b *StaticGetBinding) Request() *flowstatev1.GetRequest { return b.request }
`, run.selection.SurfaceName, run.selection.Usage, workflow.selection.GoField, run.selection.SurfaceName, run.selection.GoField)
	formatted, err := format.Source([]byte(source))
	if err != nil {
		return fmt.Errorf("schema interface pilot: format generated static binding: %w", err)
	}
	_, err = out.Write(formatted)
	return err
}
