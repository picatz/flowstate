// The comments a schema is written with, made available to a descriptor that
// travels.
//
// protoc strips SourceCodeInfo from what a .pb.go embeds, so the descriptor a
// process holds at run time carries shape and no prose. protoc-gen-flowstate-doc
// generates the comments as Go source instead, registered with
// [github.com/picatz/flowstate/pkg/flowstate/v1/protodoc/registry]; this
// repository's own schema is read that way, by
// [github.com/picatz/flowstate/pkg/flowstate/v1/protodoc]. A plugin has the same
// problem: its author's field comments could not reach an editor, however well
// the .proto was written (#723).
//
// This is the same registry, read by whoever is about to serialize a descriptor
// rather than by whoever renders it (#2148), or a `buf build` descriptor set, the
// older way of carrying the same prose. The prose rides in the descriptor bytes
// the manifest already carried, so nothing new travels and no second channel exists
// to disagree with the first.

// The bounds on a serialized descriptor, in the package both sides of the
// plugin boundary import.
//
// They are the numbers [github.com/picatz/flowstate/pkg/flowstate/v1/plugin]'s
// Config applies to a descriptor arriving from a plugin, defined here so the
// side that *writes* one bounds it with the same value. The host's bound is not
// a substitute for this one — it is applied after these bytes have already been
// unmarshaled in the plugin's own process — and a second pair of constants would
// be one bound wearing two numbers.
const (
	// DefaultMaxDescriptorBytes bounds one serialized descriptor: the bytes a
	// plugin sends, and the descriptor set it reads for the comments to attach
	// to them.
	DefaultMaxDescriptorBytes = 1 << 20 // 1 MiB

	// DefaultMaxDescriptorFiles bounds how many files one of those may carry.
	// Depth bounds do not stop breadth explosions, so this bounds breadth and
	// the reader's own depth bound bounds depth.
	DefaultMaxDescriptorFiles = 256
)

// DescriptorProse is a source of comments for descriptors about to be
// serialized: either the comments protoc-gen-flowstate-doc generated into this
// binary ([GeneratedDescriptorProse]), or those of a `buf build` descriptor set
// ([ParseDescriptorProse]), keyed by the file path they describe.
//
// The zero value and a nil pointer are both usable and both mean "no prose",
// which is the documented fallback rather than an error: a build that ships no
// prose behaves exactly as every build did before this existed.
type DescriptorProse struct {
	// byPath holds only what this type is for. The shapes in the set are
	// deliberately dropped: the descriptor that travels is the one this process
	// linked and decodes with, and a set read off disk is a *documentation*
	// source, never a source of truth about a type's fields.
	byPath map[string]*descriptorpb.FileDescriptorProto

	// generated reads the comments registered with [registry] instead.
	generated bool
}

// GeneratedDescriptorProse returns the prose protoc-gen-flowstate-doc generated
// into this binary: every comment registered with
// [github.com/picatz/flowstate/pkg/flowstate/v1/protodoc/registry] by a linked
// .doc.pb.go file.
//
// Unlike a descriptor set read off disk, these comments cannot describe a
// different revision of the schema than the one linked: they are generated by
// the same `buf generate` as the .pb.go, and they are keyed by full name
// rather than by position, so a comment that is present is attached to the
// declaration it was written for. A file with no registered comments travels
// without prose, as it would with nil prose.
func GeneratedDescriptorProse() *DescriptorProse {
	return &DescriptorProse{generated: true}
}

// ParseDescriptorProse reads a serialized FileDescriptorSet built with source
// info retained — the output of `buf build --exclude-imports -o <file>` — into
// the prose [MessageDescriptorBytesWithProse] attaches.
//
// Empty bytes parse to nil prose and no error, so an embedded artifact a build
// left empty degrades to the fallback rather than failing a plugin at startup.
// Bytes that are not a descriptor set, or a set carrying no file, are an error:
// that is an author's build being wrong about its own schema, and it is worth
// hearing about once at startup rather than never.
//
// This is exported, and an exported parser of a serialized descriptor is a
// parser somebody will hand bytes it did not build — a file discovered at run
// time, an artifact a build system fetched, a set from elsewhere. So it is
// bounded in the two resources those bytes decide: size, before anything is
// unmarshaled, and file count after, which the size bound is what makes finite.
// The numbers are [DefaultMaxDescriptorBytes] and [DefaultMaxDescriptorFiles] —
// the ones a host applies to the descriptor these comments end up inside — so a
// set too large to be accepted at the far end is refused here, at the author's
// own startup, rather than carried that far (#874 review).
func ParseDescriptorProse(raw []byte) (*DescriptorProse, error) {
	if len(raw) == 0 {
		return nil, nil
	}

	if len(raw) > DefaultMaxDescriptorBytes {
		return nil, fmt.Errorf(
			"reading a descriptor set for its comments: it is %d bytes, over the %d byte limit",
			len(raw), DefaultMaxDescriptorBytes,
		)
	}

	set := &descriptorpb.FileDescriptorSet{}
	if err := proto.Unmarshal(raw, set); err != nil {
		return nil, fmt.Errorf("reading a descriptor set for its comments: %w", err)
	}
	if len(set.GetFile()) == 0 {
		return nil, fmt.Errorf("reading a descriptor set for its comments: it holds no files")
	}
	if len(set.GetFile()) > DefaultMaxDescriptorFiles {
		return nil, fmt.Errorf(
			"reading a descriptor set for its comments: it holds %d files, over the %d file limit",
			len(set.GetFile()), DefaultMaxDescriptorFiles,
		)
	}

	prose := &DescriptorProse{byPath: make(map[string]*descriptorpb.FileDescriptorProto, len(set.GetFile()))}
	for _, file := range set.GetFile() {
		if file.GetName() == "" {
			continue
		}
		prose.byPath[file.GetName()] = file
	}

	return prose, nil
}

// sourceInfoFor returns the comments describing a file, or nil when this prose
// has nothing to say about it.
//
// For generated prose the comments are looked up by name, so the rest of this
// comment does not apply to it. For a descriptor set, nil is returned for three
// distinct reasons, and all three are the same answer
// on purpose: there is no prose at all, there is none for this path, or the file
// it describes is no longer the file being serialized. The last is the one worth
// having. A SourceCodeInfo location addresses a declaration by *index* — message
// 0, field 2 — so grafting one file's comments onto another's shape does not
// fail, it silently attributes a sentence to the wrong field, and a comment
// describing a neighbouring field is worse than no comment at all. Prose built
// from a .proto that has since moved on is therefore dropped rather than
// applied.
func (p *DescriptorProse) sourceInfoFor(file protoreflect.FileDescriptor, fdp *descriptorpb.FileDescriptorProto) *descriptorpb.SourceCodeInfo {
	if p == nil || fdp == nil {
		return nil
	}
	if p.generated {
		return generatedSourceInfo(file)
	}

	described, ok := p.byPath[fdp.GetName()]
	if !ok {
		return nil
	}
	if !sameDeclarations(described, fdp) {
		return nil
	}

	return described.GetSourceCodeInfo()
}

// sameDeclarations reports whether two descriptions of one file declare the same
// things in the same order.
//
// Not [proto.Equal] on the pair, which is the obvious spelling and answers a
// different question: `buf build` records its own metadata in an unknown field
// and populates json_name where a linked descriptor need not, so two faithful
// descriptions of one unchanged .proto are routinely unequal. What matters here
// is narrower and is exactly what a SourceCodeInfo path walks — the ordered tree
// of messages, nested messages, enums, enum values and fields — so that is what
// is compared. Anything a comment cannot be attached to is not compared, because
// a difference there cannot misplace one.
func sameDeclarations(a, b *descriptorpb.FileDescriptorProto) bool {
	if a.GetPackage() != b.GetPackage() {
		return false
	}
	if len(a.GetMessageType()) != len(b.GetMessageType()) || len(a.GetEnumType()) != len(b.GetEnumType()) {
		return false
	}
	for i, msg := range a.GetMessageType() {
		if !sameMessage(msg, b.GetMessageType()[i]) {
			return false
		}
	}
	for i, enum := range a.GetEnumType() {
		if !sameEnum(enum, b.GetEnumType()[i]) {
			return false
		}
	}

	return true
}

// sameMessage is [sameDeclarations] for one message, including everything nested
// inside it.
func sameMessage(a, b *descriptorpb.DescriptorProto) bool {
	if a.GetName() != b.GetName() {
		return false
	}
	if len(a.GetField()) != len(b.GetField()) ||
		len(a.GetNestedType()) != len(b.GetNestedType()) ||
		len(a.GetEnumType()) != len(b.GetEnumType()) {
		return false
	}
	for i, field := range a.GetField() {
		other := b.GetField()[i]
		if field.GetName() != other.GetName() || field.GetNumber() != other.GetNumber() {
			return false
		}
	}
	for i, nested := range a.GetNestedType() {
		if !sameMessage(nested, b.GetNestedType()[i]) {
			return false
		}
	}
	for i, enum := range a.GetEnumType() {
		if !sameEnum(enum, b.GetEnumType()[i]) {
			return false
		}
	}

	return true
}

// sameEnum is [sameDeclarations] for one enum.
func sameEnum(a, b *descriptorpb.EnumDescriptorProto) bool {
	if a.GetName() != b.GetName() || len(a.GetValue()) != len(b.GetValue()) {
		return false
	}
	for i, value := range a.GetValue() {
		other := b.GetValue()[i]
		if value.GetName() != other.GetName() || value.GetNumber() != other.GetNumber() {
			return false
		}
	}

	return true
}

// generatedSourceInfo builds the SourceCodeInfo a linked file would have
// carried, from the comments registered for it, or nil when none are.
//
// A location is only as precise as it needs to be for a reader to attach the
// comment: its path addresses the declaration, and its span is the smallest
// valid one, since no line numbers were generated. A comment is attached only
// when it was registered by this file, so a same-named declaration elsewhere
// cannot lend it prose.
func generatedSourceInfo(file protoreflect.FileDescriptor) *descriptorpb.SourceCodeInfo {
	if file == nil {
		return nil
	}

	var locations []*descriptorpb.SourceCodeInfo_Location
	add := func(d protoreflect.Descriptor, path []int32) {
		leading, from, ok := registry.Lookup(d.FullName())
		if !ok || from != file.Path() {
			return
		}
		locations = append(locations, &descriptorpb.SourceCodeInfo_Location{
			Path:            slices.Clone(path),
			Span:            []int32{0, 0, 0},
			LeadingComments: proto.String(leading),
		})
	}

	enum := func(e protoreflect.EnumDescriptor, path []int32) {
		add(e, path)
		for i := range e.Values().Len() {
			add(e.Values().Get(i), append(path, sourcePath.enumValue, int32(i)))
		}
	}
	var message func(m protoreflect.MessageDescriptor, path []int32)
	message = func(m protoreflect.MessageDescriptor, path []int32) {
		add(m, path)
		for i := range m.Fields().Len() {
			add(m.Fields().Get(i), append(path, sourcePath.messageField, int32(i)))
		}
		for i := range m.Oneofs().Len() {
			add(m.Oneofs().Get(i), append(path, sourcePath.messageOneof, int32(i)))
		}
		for i := range m.Extensions().Len() {
			add(m.Extensions().Get(i), append(path, sourcePath.messageExtension, int32(i)))
		}
		for i := range m.Messages().Len() {
			message(m.Messages().Get(i), append(path, sourcePath.messageNested, int32(i)))
		}
		for i := range m.Enums().Len() {
			enum(m.Enums().Get(i), append(path, sourcePath.messageEnum, int32(i)))
		}
	}

	for i := range file.Messages().Len() {
		message(file.Messages().Get(i), []int32{sourcePath.fileMessage, int32(i)})
	}
	for i := range file.Enums().Len() {
		enum(file.Enums().Get(i), []int32{sourcePath.fileEnum, int32(i)})
	}
	for i := range file.Extensions().Len() {
		add(file.Extensions().Get(i), []int32{sourcePath.fileExtension, int32(i)})
	}
	for i := range file.Services().Len() {
		service := file.Services().Get(i)
		path := []int32{sourcePath.fileService, int32(i)}
		add(service, path)
		for j := range service.Methods().Len() {
			add(service.Methods().Get(j), append(path, sourcePath.serviceMethod, int32(j)))
		}
	}

	if len(locations) == 0 {
		return nil
	}
	return &descriptorpb.SourceCodeInfo{Location: locations}
}

// sourcePath holds the descriptor.proto field numbers a SourceCodeInfo path is
// built from, read off descriptorpb's own descriptors rather than written out,
// so they cannot disagree with the schema that defines them.
var sourcePath = struct {
	fileMessage, fileEnum, fileService, fileExtension                        int32
	messageField, messageNested, messageEnum, messageExtension, messageOneof int32
	enumValue, serviceMethod                                                 int32
}{
	fileMessage:      fieldNumber(&descriptorpb.FileDescriptorProto{}, "message_type"),
	fileEnum:         fieldNumber(&descriptorpb.FileDescriptorProto{}, "enum_type"),
	fileService:      fieldNumber(&descriptorpb.FileDescriptorProto{}, "service"),
	fileExtension:    fieldNumber(&descriptorpb.FileDescriptorProto{}, "extension"),
	messageField:     fieldNumber(&descriptorpb.DescriptorProto{}, "field"),
	messageNested:    fieldNumber(&descriptorpb.DescriptorProto{}, "nested_type"),
	messageEnum:      fieldNumber(&descriptorpb.DescriptorProto{}, "enum_type"),
	messageExtension: fieldNumber(&descriptorpb.DescriptorProto{}, "extension"),
	messageOneof:     fieldNumber(&descriptorpb.DescriptorProto{}, "oneof_decl"),
	enumValue:        fieldNumber(&descriptorpb.EnumDescriptorProto{}, "value"),
	serviceMethod:    fieldNumber(&descriptorpb.ServiceDescriptorProto{}, "method"),
}

func fieldNumber(m proto.Message, name protoreflect.Name) int32 {
	return int32(m.ProtoReflect().Descriptor().Fields().ByName(name).Number())
}
