// The analysis driver writes one JSON object per analysed package,
// concatenated rather than wrapped in an array, and writes `{}` for the
// packages with nothing to say. A parser that expects a single document
// reads the first object and silently reports a fraction of the tree, which
// is the failure that matters here: an advisory report that under-counts
// looks exactly like a clean one.
func TestParseReportReadsEveryObjectInTheStream(t *testing.T) {
	stream := `{}
{
	"example.com/a": {
		"minmax": [
			{"posn": "/repo/a/a.go:10:2", "message": "if/else can be min"}
		]
	}
}
{}
{
	"example.com/b": {
		"slicescontains": [
			{"posn": "/repo/b/b.go:3:1", "message": "loop can be slices.Contains"},
			{"posn": "/repo/b/b.go:9:1", "message": "loop can be slices.Contains"}
		],
		"minmax": [
			{"posn": "/repo/b/c.go:1:1", "message": "if/else can be max"}
		]
	}
}`

	rep, err := parseReport(strings.NewReader(stream))
	if err != nil {
		t.Fatalf("parseReport: %v", err)
	}
	if rep.total != 4 {
		t.Errorf("total sites = %d, want 4 (a trailing object was dropped)", rep.total)
	}
	if got := len(rep.files); got != 3 {
		t.Errorf("files = %d, want 3", got)
	}
	if got := len(rep.packages); got != 2 {
		t.Errorf("packages = %d, want 2", got)
	}
	if got := rep.packages["example.com/b"]; got != 3 {
		t.Errorf("example.com/b sites = %d, want 3", got)
	}
	if got := rep.fixers["minmax"].sites; got != 2 {
		t.Errorf("minmax sites = %d, want 2 (counts must accumulate across packages)", got)
	}
	if got := rep.fixers["slicescontains"].sites; got != 2 {
		t.Errorf("slicescontains sites = %d, want 2", got)
	}
	if got := len(rep.listing); got != 4 {
		t.Errorf("listing = %d entries, want 4", got)
	}
}

// A site in a generated file is not actionable — CLAUDE.md's rule is that
// generated files are never hand-edited — so it is counted separately and
// kept out of the fixer, package and file totals. `go fix` itself does not
// make this distinction, which is why the report has to.
func TestParseReportSeparatesGeneratedFiles(t *testing.T) {
	dir := t.TempDir()
	gen := filepath.Join(dir, "thing.pb.go")
	writeFile(t, gen, "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage p\n")
	hand := filepath.Join(dir, "thing.go")
	writeFile(t, hand, "package p\n")

	stream := `{"example.com/p": {"reflecttypefor": [
		{"posn": "` + gen + `:5:5", "message": "TypeOf can be TypeFor"},
		{"posn": "` + hand + `:6:6", "message": "TypeOf can be TypeFor"}
	]}}`

	rep, err := parseReport(strings.NewReader(stream))
	if err != nil {
		t.Fatalf("parseReport: %v", err)
	}
	if rep.total != 1 {
		t.Errorf("actionable total = %d, want 1", rep.total)
	}
	if rep.generated != 1 {
		t.Errorf("generated total = %d, want 1", rep.generated)
	}
	if got := rep.fixers["reflecttypefor"]; got.sites != 1 || got.generated != 1 {
		t.Errorf("reflecttypefor = %d actionable / %d generated, want 1 / 1", got.sites, got.generated)
	}
	if rep.files[gen] {
		t.Error("a generated file was counted among the files holding actionable sites")
	}
	if rep.packages["example.com/p"] != 1 {
		t.Errorf("package sites = %d, want 1", rep.packages["example.com/p"])
	}
}

// The marker only counts above the package clause. A file that merely
// mentions the phrase in a comment or a string further down — this
// repository has several that talk about generated code — is hand-written,
// and excluding it would hide real sites from the report.
func TestIsGenerated(t *testing.T) {
	dir := t.TempDir()
	cases := []struct {
		name string
		body string
		want bool
	}{
		{"protoc header", "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage p\n", true},
		{"after a build tag and blank lines", "//go:build linux\n\n// Code generated by stringer. DO NOT EDIT.\npackage p\n", true},
		{"hand written", "// Package p does things.\npackage p\n", false},
		{"phrase below the package clause", "package p\n\n// Code generated files are never edited by hand. DO NOT EDIT.\nvar x = 1\n", false},
		{"marker without the DO NOT EDIT suffix", "// Code generated from a schema, then edited\npackage p\n", false},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			path := filepath.Join(dir, strings.ReplaceAll(tc.name, " ", "_")+".go")
			writeFile(t, path, tc.body)
			if got := isGenerated(path); got != tc.want {
				t.Errorf("isGenerated(%q) = %v, want %v", tc.body, got, tc.want)
			}
		})
	}

	if isGenerated(filepath.Join(dir, "nonexistent.go")) {
		t.Error("a file that cannot be read must not be treated as generated")
	}
	if isGenerated(filepath.Join(dir, "workflow.yaml")) {
		t.Error("only .go files can carry the marker")
	}
}

func TestFileOfStripsLineAndColumn(t *testing.T) {
	cases := map[string]string{
		"/repo/a/a.go:10:2": "/repo/a/a.go",
		"a.go:1:1":          "a.go",
		"C:/repo/a.go:10:2": "C:/repo/a.go",
		"/repo/a/a.go":      "/repo/a/a.go", // malformed input degrades, never panics
		"noseparatorsatall": "noseparatorsatall",
	}
	for in, want := range cases {
		if got := fileOf(in); got != want {
			t.Errorf("fileOf(%q) = %q, want %q", in, got, want)
		}
	}
}

// The report is what a weekly job files into an issue, so it has to carry
// the decision alongside the numbers: the numbers are precisely what tempt
// the reader into the sweep #521 forbids.
func TestWriteReportCarriesTheCountsAndThePolicy(t *testing.T) {
	rep, err := parseReport(strings.NewReader(`{"example.com/a": {"minmax": [
		{"posn": "/repo/a/a.go:10:2", "message": "if/else can be min"}
	]}}`))
	if err != nil {
		t.Fatalf("parseReport: %v", err)
	}
	var sb strings.Builder
	writeReport(&sb, rep, []string{"./..."}, true)
	out := sb.String()

	for _, want := range []string{
		"1 site(s)",
		"| `minmax` | 1 |",
		"| `example.com/a` | 1 |",
		"/repo/a/a.go:10:2: [minmax] if/else can be min",
		"never as a sweep",
		"flow fix",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("report is missing %q:\n%s", want, out)
		}
	}
}

func TestWriteReportOnACleanTree(t *testing.T) {
	rep, err := parseReport(strings.NewReader(`{}{}`))
	if err != nil {
		t.Fatalf("parseReport: %v", err)
	}
	var sb strings.Builder
	writeReport(&sb, rep, []string{"./..."}, false)
	if got := sb.String(); !strings.Contains(got, "Nothing to report") {
		t.Errorf("clean tree report = %q, want it to say there is nothing to report", got)
	}
}

// The failure this guards is the one that looks like success. When a package
// fails to load, `go fix -json` exits non-zero and writes the compiler's
// message to stderr — but stdout still carries well-formed JSON for every
// package that *did* analyse, and nothing in that stream says anyone is
// missing. Rendering it produces a plausible report that is short by an
// unknown amount, which for an advisory whose entire content is a count is
// indistinguishable from a clean tree.
//
// The fixture is the real thing: stdout and stderr captured from `go fix
// -json ./...` over a two-package module whose second package does not
// parse.
func TestALoadFailureRefusesTheReportAndNamesThePackages(t *testing.T) {
	// Verbatim stderr from the observed run.
	const stderr = "# example.com/broken/bad\n" +
		"fix: bad/bad.go:3:17: expected ';', found is\n"
	// Verbatim stdout from the same run: the good package's diagnostics,
	// complete and well-formed, with no trace of the package that failed.
	const stdout = `{"example.com/broken/good": {"reflecttypefor": [
		{"posn": "/repo/good/good.go:5:37", "message": "reflect.TypeOf call can be simplified using TypeFor"}
	]}}`

	// Read on its own, the partial stream parses perfectly and reports one
	// site. That is exactly why the stream cannot be the thing that decides.
	rep, err := parseReport(strings.NewReader(stdout))
	if err != nil {
		t.Fatalf("parseReport: %v", err)
	}
	if rep.total != 1 {
		t.Fatalf("partial stream total = %d, want 1 (fixture no longer represents a partial report)", rep.total)
	}

	err = incompleteAnalysisError(1, stderr, len(stdout))
	if err == nil {
		t.Fatal("a non-zero exit must refuse the report")
	}
	msg := err.Error()
	for _, want := range []string{
		"example.com/broken/bad",
		"No report is printed",
		"discarded",
	} {
		if !strings.Contains(msg, want) {
			t.Errorf("error is missing %q:\n%s", want, msg)
		}
	}
}

func TestFailedPackages(t *testing.T) {
	cases := []struct {
		name   string
		stderr string
		want   []string
	}{
		{
			name:   "one package",
			stderr: "# example.com/broken/bad\nfix: bad/bad.go:3:17: expected ';', found is\n",
			want:   []string{"example.com/broken/bad"},
		},
		{
			name:   "several, including a test variant, deduplicated and in order",
			stderr: "# a/b\nerr\n# a/c [a/c.test]\nerr\n# a/b\nerr\n",
			want:   []string{"a/b", "a/c [a/c.test]"},
		},
		{
			// Progress output carries no headers, so nothing is named — and
			// the caller still refuses the report, because the exit code is
			// what decides, not this.
			name:   "download progress only",
			stderr: "go: downloading example.com/m v1.2.3\n",
			want:   nil,
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			got := failedPackages(tc.stderr)
			if len(got) != len(tc.want) {
				t.Fatalf("failedPackages = %q, want %q", got, tc.want)
			}
			for i := range got {
				if got[i] != tc.want[i] {
					t.Fatalf("failedPackages = %q, want %q", got, tc.want)
				}
			}
		})
	}
}

// Findings are not failures: `go fix -json` exits 0 with diagnostics on
// stdout, unlike `go fix -diff`, whose "non-zero means non-empty" convention
// this command must not inherit. This exercises the real binary over a
// module written for the purpose, so a toolchain that changed that
// convention is caught here rather than by a weekly report that has quietly
// become an error.
func TestRunGoFixOnAWorkingModule(t *testing.T) {
	if testing.Short() {
		t.Skip("runs the go command")
	}
	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, "go.mod"), "module example.com/works\n\ngo 1.26\n")
	writeFile(t, filepath.Join(dir, "works.go"), "package works\n\nimport \"reflect\"\n\nfunc F(x int) reflect.Type { return reflect.TypeOf(x) }\n")

	t.Chdir(dir)
	out, err := runGoFix([]string{"./..."})
	if err != nil {
		t.Fatalf("runGoFix over a module that builds: %v", err)
	}
	rep, err := parseReport(strings.NewReader(out))
	if err != nil {
		t.Fatalf("parseReport: %v", err)
	}
	if rep.total != 1 {
		t.Errorf("total = %d, want 1 (the reflect.TypeOf site)", rep.total)
	}
}

// And the other side of it, end to end: a module with a package that does
// not parse produces an error rather than a report, even though the go
// command writes usable JSON for the package that did analyse.
func TestRunGoFixRefusesAModuleThatDoesNotLoad(t *testing.T) {
	if testing.Short() {
		t.Skip("runs the go command")
	}
	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, "go.mod"), "module example.com/broken\n\ngo 1.26\n")
	for _, sub := range []string{"good", "bad"} {
		if err := os.MkdirAll(filepath.Join(dir, sub), 0o750); err != nil {
			t.Fatal(err)
		}
	}
	writeFile(t, filepath.Join(dir, "good", "good.go"), "package good\n\nimport \"reflect\"\n\nfunc F(x int) reflect.Type { return reflect.TypeOf(x) }\n")
	writeFile(t, filepath.Join(dir, "bad", "bad.go"), "package bad\n\nfunc G() { this is not go }\n")

	t.Chdir(dir)
	out, err := runGoFix([]string{"./..."})
	if err == nil {
		t.Fatalf("runGoFix returned a report for a module that does not load:\n%s", out)
	}
	if !strings.Contains(err.Error(), "example.com/broken/bad") {
		t.Errorf("error does not name the package that failed to analyse:\n%s", err)
	}
	if out != "" {
		t.Errorf("a refused run must return no output, got %d bytes", len(out))
	}
}

func writeFile(t *testing.T, path, body string) {
	t.Helper()
	if err := os.WriteFile(path, []byte(body), 0o600); err != nil {
		t.Fatalf("writing %s: %v", path, err)
	}
}
